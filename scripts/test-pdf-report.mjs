import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {buildReport} from '../pdf-report.js';
const data=JSON.parse(await fs.readFile(new URL('../data.json',import.meta.url),'utf8'));
const options={data,generatedAt:'2026-10-09T03:10:00Z'};
const html=buildReport(options);
assert.equal((html.match(/class="report-page"/g)||[]).length,12);
assert.equal((html.match(/data-report-indicator=/g)||[]).length,100);
assert.ok(html.indexOf('<h1>세계 주요 증시</h1>')<html.indexOf('<h1>국채 금리 · 초단기</h1>'));
assert.ok(!html.includes('경제 지표 리포트')&&!html.includes('주요 지표 비교')&&!html.includes('시장 한눈에')&&!html.includes('<svg'));
for(let page=1;page<=12;page++)assert.ok(html.includes(`${page} / 12`));
for(const item of data.indicators)assert.ok(html.includes(`data-report-indicator="${item.id}"`));
assert.equal((html.match(/<th scope="col">12개월/g)||[]).length,13,'Every category and stock/bond subcategory retains all comparison periods');
for(const group of ['미국 섹터','한국 섹터','미국 팩터','한국 팩터'])assert.ok(html.includes(`<h1>${group}</h1>`));
assert.ok(html.includes('분배금을 제외한 가격 변화율'));
for(const group of ['초단기','단기','중기','장기','초장기'])assert.ok(html.includes(`<h1>국채 금리 · ${group}</h1>`));
assert.ok(html.includes('한국의 1년 미만 국채 금리는 연결 출처에 없어'));
const originalBondIds=new Set(['kr1','kr3','kr10','kr30','us1','us3','us10','us30','jp1','jp3','jp10','jp30']);
const oldData={...data,indicators:data.indicators.filter(item=>item.instrument!=='etf'&&(item.category!=='bonds'||originalBondIds.has(item.id))).map(({bondGroup,...item})=>item)};
assert.equal((buildReport({...options,data:oldData}).match(/class="report-page"/g)||[]).length,4,'The original indicator universe retains its four-page layout');
assert.ok(html.includes('bp)')&&html.includes('2025.10.13'),'Bond differences and actual annual observation dates are retained');
assert.ok(html.includes('보고서 작성 2026.10.09 12:10 KST'));
const broken=structuredClone(data);
const btc=broken.indicators.find(i=>i.id==='btc');
btc.name='<img src=x onerror="alert(1)">';btc.refreshError='Timed out';btc.values.quarter=null;btc.dates.quarter=null;
const missing=buildReport({...options,data:broken});
assert.ok(missing.includes('report-error report-failed">조회 실패'));
assert.ok(missing.includes('&lt;img src=x onerror=&quot;alert(1)&quot;&gt;'));
assert.ok(!missing.includes('<img src=x'));
assert.ok(!missing.includes('NaN')&&!missing.includes('undefined'));
console.log('PASS: 12 report pages with stock/bond groups, 100 indicators, all periods, original layout compatibility, dates, bp, missing/stale data and escaped text.');
