import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {buildReport} from '../pdf-report.js';
const data=JSON.parse(await fs.readFile(new URL('../data.json',import.meta.url),'utf8'));
const options={data,selected:'btc',compared:'gold',chartStart:'quarter',pulsePeriod:'month',generatedAt:'2026-10-09T03:10:00Z'};
const html=buildReport(options);
assert.equal((html.match(/class="report-page"/g)||[]).length,5);
assert.equal((html.match(/data-report-indicator=/g)||[]).length,36);
for(const item of data.indicators)assert.ok(html.includes(`data-report-indicator="${item.id}"`));
assert.ok(html.includes('data-report-series="btc"')&&html.includes('data-report-series="gold"'));
assert.ok(html.includes('3개월 전부터')&&html.includes('1개월 대비 · 전체 지표'));
assert.ok(html.includes('5개 비교 시점'));
assert.ok(!html.includes('>12개월 전</text>'),'Chart must start at the selected period');
assert.equal((html.match(/<th scope="col">12개월/g)||[]).length,5,'Every category retains all comparison periods');
assert.ok(html.includes('bp)')&&html.includes('2025.10.02'),'Bond differences and actual annual observation dates are retained');
assert.ok(html.includes('보고서 작성 2026.10.09 12:10 KST'));
const broken=structuredClone(data);
const btc=broken.indicators.find(i=>i.id==='btc');
btc.name='<img src=x onerror="alert(1)">';btc.refreshError='Timed out';btc.values.quarter=null;btc.dates.quarter=null;
const missing=buildReport({...options,data:broken});
assert.ok(missing.includes('조회 실패 1개는 이전 확인값 사용'));
assert.ok(missing.includes('조회 실패 · 이전 확인값'));
assert.ok(missing.includes('3개월 전 기준값이 없거나 0이므로'));
assert.ok(!missing.includes('data-report-series='),'Missing comparison baseline must not draw a misleading chart');
assert.ok(missing.includes('&lt;img src=x onerror=&quot;alert(1)&quot;&gt;'));
assert.ok(!missing.includes('<img src=x'));
assert.ok(!missing.includes('NaN')&&!missing.includes('undefined'));
console.log('PASS: 36 indicators, selected graph/periods, actual dates, bp, missing/stale data and escaped text.');
